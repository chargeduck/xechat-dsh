/** 消息头里的占位符：{{pf:WEB}}，渲染时被替换成对应图标 */
export const PLATFORM_TOKEN_RE = /\{\{pf:([A-Z]+)\}\}/g

/** 取平台图标 SVG，未知平台返回空串 */
export function platformSvg(p) {
  return PLATFORM_ICONS[p] || ''
}

/** 取平台中文名，未知平台原样返回 */
export function platformLabel(p) {
  return PLATFORM_LABELS[p] || p || '未知平台'
}

/** 生成消息头占位符（纯文本消息里用，渲染阶段再换成 SVG） */
export function platformMark(p) {
  return PLATFORM_ICONS[p] ? '{{pf:' + p + '}}' : ''
}

/** 把消息里的占位符替换成真实图标 */
export function parsePlatformMarkup(html) {
  return String(html || '').replace(PLATFORM_TOKEN_RE, (m, key) => PLATFORM_ICONS[key] || '')
}

/**
 * 当前运行平台。
 * 由宿主在页面脚本执行前写入 window.__XECHAT_PLATFORM__：
 * - VS Code 扩展注入 'VSCODE'
 * - DSH 插件注入 'DSH'
 * 直接开浏览器访问时没有该变量，回落 'WEB'。
 */
export function currentPlatform() {
  if (typeof window !== 'undefined' && window.__XECHAT_PLATFORM__) {
    return String(window.__XECHAT_PLATFORM__)
  }
  return 'WEB'
}
